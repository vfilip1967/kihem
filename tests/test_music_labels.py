class ShortMusicLabelTests(unittest.TestCase):
    def test_owner_examples(self):
        self.assertEqual(
            short_music_label(
                "Κοινωνικόν «Ἀγαλλιᾶσθε δίκαιοι», ἦχος α΄ · Ἀνδρέου Τσικνοπούλου (ψηφιακή)"
            ),
            "Κοιν. α΄ ψηφ.",
        )
        self.assertEqual(
            short_music_label("Χερουβικόν … ἦχος πλ. α΄ … (ψηφιακή)"),
            "Χερ. πλ.α΄ ψηφ.",
        )

    def test_genre_abbreviations(self):
        cases = {
            "Χερουβικὸν · σύντομον · ἦχος α΄ · Μελωδός": "Χερ. σύντ. α΄",
            "Κοινωνικόν · ἦχος β΄": "Κοιν. β΄",
            "Τρισάγιος ὕμνος · ἦχος β΄": "Τρισ. β΄",
            "Ὁ Μονογενής, ἦχος β΄": "Μονογ. β΄",
            "Ἀπολυτίκιον · ἦχος δ΄": "Απολ. δ΄",
            "Κοντάκιον · ἦχος γ΄": "Κοντ. γ΄",
            "Δύναμις · ἦχος α΄": "Δύν. α΄",
            "Ἀλληλούϊα · ἦχος πλ. α΄": "Ἀλλ. πλ.α΄",
            "Ἄξιόν ἐστιν · ἦχος βαρύς": "Ἄξ. βαρ.",
            "Εἰσοδικόν · ἦχος δ΄": "Εἰσ. δ΄",
            "Προκείμενον · ἦχος πλ. δ΄": "Προκ. πλ.δ΄",
            "Ἀντίφωνον · ἦχος β΄": "Ἀντ. β΄",
        }
        for title, expected in cases.items():
            with self.subTest(title=title):
                self.assertEqual(short_music_label(title), expected)

    def test_variant_markers_disambiguate_settings(self):
        cases = {
            "Τρισάγιος ὕμνος · ἀργός (κλασικά), ἦχος β΄ (ψηφιακή)": "Τρισ. αργ. β΄ ψηφ.",
            "Τρισάγιος ὕμνος · σύντομος, ἦχος β΄ · Γεωργίου Πρωγάκη (ψηφιακή)": "Τρισ. σύντ. β΄ ψηφ.",
            "Χερουβικὸν · σύντομον · ἦχος πλ. δ΄ · Μελωδός": "Χερ. σύντ. πλ.δ΄",
        }
        for title, expected in cases.items():
            with self.subTest(title=title):
                self.assertEqual(short_music_label(title), expected)
                self.assertLessEqual(len(expected), 24)

    def test_unknown_genre_uses_two_significant_words(self):
        cases = {
            "Κύριε ἐλέησον · σύντομα": "Κύρι. ἐλέη.",
            "Ταῖς πρεσβείαις": "Ταῖς. πρεσ.",
            "Σῶσον ἡμᾶς": "Σῶσο. ἡμᾶς.",
        }
        for title, expected in cases.items():
            with self.subTest(title=title):
                self.assertEqual(short_music_label(title), expected)
                self.assertLessEqual(len(expected), 24)

    def test_tone_short_forms(self):
        cases = {
            "Χερουβικόν · ἦχος α΄": "Χερ. α΄",
            "Χερουβικόν · ἦχος β΄": "Χερ. β΄",
            "Χερουβικόν · ἦχος γ΄": "Χερ. γ΄",
            "Χερουβικόν · ἦχος δ΄": "Χερ. δ΄",
            "Χερουβικόν · ἦχος πλ. α΄": "Χερ. πλ.α΄",
            "Χερουβικόν · ἦχος πλ. β΄": "Χερ. πλ.β΄",
            "Χερουβικόν · ἦχος βαρύς": "Χερ. βαρ.",
            "Χερουβικόν · ἦχος πλ. δ΄": "Χερ. πλ.δ΄",
            "Μεγάλη Δοξολογία, πλ. β΄": "Μεγά. Δοξο. πλ.β΄",
            "Ἡ Τιμιωτέρα, δ΄ ἦχος": "Τιμι. δ΄",
        }
        for title, expected in cases.items():
            with self.subTest(title=title):
                self.assertEqual(short_music_label(title), expected)

    def test_digital_marker_only_for_digital_titles(self):
        self.assertEqual(short_music_label("Ἄξιόν ἐστιν · ἦχος βαρύς (ψηφιακή)"), "Ἄξ. βαρ. ψηφ.")
        self.assertEqual(short_music_label("Ἄξιόν ἐστιν · ἦχος βαρύς (Ψηφιακή)"), "Ἄξ. βαρ. ψηφ.")
        self.assertEqual(short_music_label("Ἄξιόν ἐστιν · ἦχος βαρύς"), "Ἄξ. βαρ.")

