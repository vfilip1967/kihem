    def test_every_label_is_short_and_non_empty(self):
        for title in REAL_TITLES:
            with self.subTest(title=title):
                label = short_music_label(title)
                self.assertTrue(label)
                self.assertLessEqual(len(label), 24)

    def test_fallback_caps_label_length(self):
        label = short_music_label("123456789012345678901234567890")
        self.assertEqual(label, "1234567890123456789012…")
        self.assertLessEqual(len(label), 24)

    def test_empty_title_still_has_a_label(self):
        self.assertEqual(short_music_label("   "), "Μουσικό")


